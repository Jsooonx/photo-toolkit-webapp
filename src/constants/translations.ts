export type TranslationType = typeof translations.en;
export const getTranslation = (lang: Language): TranslationType => translations[lang] || translations.id;
export const formatBytes = (bytes: number, decimals = 2) => {
  if (bytes === 0) return '0 Bytes';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['Bytes', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
};
export const getSavingPercentage = (original: number, processed: number): number => {
  if (!original) return 0;
  const saving = original - processed;
  const percentage = (saving / original) * 100;
  return Math.max(0, Math.round(percentage));
};
